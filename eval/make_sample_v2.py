#!/usr/bin/env python3
"""Build a sample.toml for rippy's scripts/jev-eval from v2 weighted labels.

    eval/make_sample_v2.py test_unseen --out data/v2/eval/test_unseen.toml

Each teacher vote is a verdict: `exfil` if it flags exfiltration, `safe` if it
is read_only with no risk flag, otherwise `unsafe`. Votes are weighted as in
training (Sonnet 1 per pass, Gemma 1, Opus adjudicator 2). A command is
labelled `safe` when at least --agree of the weight says safe, `exfil` when at
least half says exfil, `unsafe` when at most 1 - --agree says safe. The rest
are dropped: where the label is uncertain it cannot mark a backend wrong.
"""

import argparse
import json
from pathlib import Path

RISKS = ["exfiltration", "writes_outside_project", "reads_secrets", "irreversible",
         "runs_project_code", "self_referential"]
TEACHERS = {"sonnet-5": 1, "gemma-4-31b": 1, "opus-adjudicator": 2}


def verdict(vote):
    if vote["exfiltration"]:
        return "exfil"
    return "safe" if vote["effect"] == "read_only" and not any(vote[k] for k in RISKS) else "unsafe"


def toml_string(s):
    return "'''" + s + "'''" if "'''" not in s else json.dumps(s)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("split")
    ap.add_argument("--labels", type=Path, default=Path("data/v2/labels"))
    ap.add_argument("--agree", type=float, default=0.75)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    weighted = {}
    for name, w in TEACHERS.items():
        path = args.labels / name / f"{args.split}.jsonl"
        if not path.exists():
            continue
        for r in map(json.loads, path.open()):
            weighted.setdefault(r["command"], []).extend((verdict(v), w) for v in r["teacher"]["votes"])
    lines = [f"# Generated by rippy-kev eval/make_sample_v2.py from {args.split} (agree >= {args.agree})."]
    counts, dropped = {}, 0
    for command in sorted(weighted):
        vs = weighted[command]
        total = sum(w for _, w in vs)
        share = {k: sum(w for v, w in vs if v == k) / total for k in ("safe", "unsafe", "exfil")}
        if share["exfil"] >= 0.5:
            label = "exfil"
        elif share["safe"] >= args.agree:
            label = "safe"
        elif share["safe"] <= 1 - args.agree:
            label = "unsafe"
        else:
            label = None
        if label is None or "\n" in command:
            dropped += 1
            continue
        counts[label] = counts.get(label, 0) + 1
        lines += ["", "[[case]]", f"command = {toml_string(command)}", f'label = "{label}"']
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n")
    print(f"{args.split}: {sum(counts.values())} cases {counts}, {dropped} dropped -> {args.out}")


if __name__ == "__main__":
    main()
