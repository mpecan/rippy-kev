#!/usr/bin/env python3
"""Turn a teacher-labelled split into a sample.toml for rippy's scripts/jev-eval.

    eval/make_sample.py test --teachers gemma-4-31b sonnet-5 --out data/eval/test-sample.toml

Labels come from teacher consensus: `safe` when every teacher calls the command
read_only with no risk, `exfil` when every teacher flags exfiltration, `unsafe`
when every teacher sees some risk. Commands the teachers split on are left out:
there the label itself is uncertain, so it cannot mark a backend wrong.
"""

import argparse
import json
from pathlib import Path

RISKS = ["exfiltration", "writes_outside_project", "reads_secrets", "irreversible",
         "runs_project_code", "self_referential"]


def verdict(vote):
    if vote["exfiltration"]:
        return "exfil"
    clean = vote["effect"] == "read_only" and not any(vote[k] for k in RISKS)
    return "safe" if clean else "unsafe"


def toml_string(s):
    return "'''" + s + "'''" if "'''" not in s else json.dumps(s)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("split")
    ap.add_argument("--teachers", nargs="+", required=True)
    ap.add_argument("--labels", type=Path, default=Path("data/labels"))
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    teachers = [{r["command"]: r["teacher"]["votes"] for r in map(json.loads, (args.labels / t / f"{args.split}.jsonl").open())}
                for t in args.teachers]
    common = sorted(set.intersection(*(set(t) for t in teachers)))
    counts, dropped, lines = {}, 0, [f"# Generated by rippy-kev eval/make_sample.py from {args.split}; consensus of {', '.join(args.teachers)}."]
    for command in common:
        labels = {verdict(v) for t in teachers for v in t[command]}
        unsafe_like = labels <= {"unsafe", "exfil"}
        label = labels.pop() if len(labels) == 1 else "unsafe" if unsafe_like else None
        if label is None or "\n" in command:
            dropped += 1
            continue
        counts[label] = counts.get(label, 0) + 1
        lines += ["", "[[case]]", f"command = {toml_string(command)}", f'label = "{label}"']
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n")
    print(f"{sum(counts.values())} cases {counts}, {dropped} dropped (teachers split safe/unsafe) -> {args.out}")


if __name__ == "__main__":
    main()
